package cmd

import (
	"fmt"
	"io"
	"strings"
	"time"

	"github.com/alecthomas/kong"
)

// writeManPage writes the leaker(1) man page in roff. The commands and
// options come from the CLI model, so the page matches this build.
func writeManPage(w io.Writer, app *kong.Application, version string, date time.Time) error {
	var b strings.Builder
	line := func(s string) { b.WriteString(s + "\n") }
	text := func(s string) { line(roffEscape(s)) }

	line(`.\" Generated by "leaker man"; do not edit.`)
	line(fmt.Sprintf(`.TH LEAKER 1 %s "leaker %s" "User Commands"`, date.Format("2006-01-02"), version))

	line(`.SH "NAME"`)
	line(`leaker \- find leaked credentials for an email, username, domain, keyword or phone number`)

	line(`.SH "SYNOPSIS"`)
	line(`\fBleaker\fR \fIcommand\fR [\fItargets\fR] [\fIflags\fR]`)
	line(".br")
	line(`\fBleaker completion\fR \fIshell\fR`)

	line(`.SH "DESCRIPTION"`)
	text(app.Help)
	line(".PP")
	text("The command sets what the targets are. A target on the command line is searched as given, " +
		"unless it names an existing file: then leaker reads targets from that file, one per line. " +
		"-l reads targets from a file, and - reads them from standard input. " +
		"With no target and no -l, leaker reads targets from standard input when it is piped.")
	line(".PP")
	text("Most sources need API keys, read from the provider config file (see FILES). " +
		"The default source group, online, skips sources without a key; -L lists the sources.")

	line(`.SH "COMMANDS"`)
	for _, c := range app.Children {
		if c.Hidden || c.Type != kong.CommandNode {
			continue
		}
		line(".TP")
		usage := `\fB` + c.Name + `\fR`
		for _, arg := range c.Positional {
			if arg.Required {
				usage += ` \fI` + arg.Name + `\fR`
			} else {
				usage += ` [\fI` + arg.Name + `\fR]`
			}
		}
		line(usage)
		text(sentence(c.Help))
		for _, arg := range c.Positional {
			text(sentence(arg.Help))
		}
	}

	line(`.SH "OPTIONS"`)
	for _, f := range app.Flags {
		if f.Hidden {
			continue
		}
		line(".TP")
		usage := `\fB` + roffEscape("--"+f.Name) + `\fR`
		if f.Short != 0 {
			usage = `\fB` + roffEscape("-"+string(f.Short)) + `\fR, ` + usage
		}
		if !f.IsBool() && !f.IsCounter() {
			usage += `=\fI` + roffEscape(f.FormatPlaceHolder()) + `\fR`
		}
		line(usage)
		text(sentence(f.Help))
	}

	line(`.SH "EXIT STATUS"`)
	for _, status := range []struct {
		code int
		text string
	}{
		{ExitOK, "The search ran, with or without leaks."},
		{ExitError, "A runtime error, including a target that no source could search, for example because every request failed."},
		{ExitUsage, "A usage or configuration error; nothing was searched. For example: no valid target, " +
			"or a source named with -s that has no API key or cannot run that search type."},
		{ExitInterrupted, "Interrupted by SIGINT or SIGTERM. A second interrupt exits at once."},
	} {
		line(".TP")
		line(fmt.Sprintf(".B %d", status.code))
		text(status.text)
	}

	line(`.SH "ENVIRONMENT"`)
	for _, env := range []struct{ name, text string }{
		{"LEAKER_PROVIDER_CONFIG", "The provider config file to use when -p is not given."},
		{"LEAKER_DB", "The local database to use when --db is not given."},
		{"LEAKER_NO_WRITE_DB", "When true or 1, results are not written to the local database, as with --no-write-db."},
		{"HTTPS_PROXY, HTTP_PROXY, NO_PROXY", "The proxy for requests when --proxy is not given."},
	} {
		line(".TP")
		line(".B " + roffEscape(env.name))
		text(env.text)
	}

	line(`.SH "FILES"`)
	line(".TP")
	line(`.I ~/.config/leaker/provider\-config.yaml`)
	text("API keys for the sources, one list per source. Created on the first run, readable only by its owner. " +
		"The directory is $XDG_CONFIG_HOME/leaker when XDG_CONFIG_HOME is set, " +
		"and ~/Library/Application Support/leaker on macOS.")
	line(".TP")
	line(`.I ~/.config/leaker/leaker.db`)
	text("The local SQLite cache of found results, in the same directory. The local source searches it.")

	line(`.SH "EXAMPLES"`)
	for i, example := range []struct{ text, command string }{
		{"Search one email address:", "leaker email jane@example.com"},
		{"Search a list of domains with every source that has a key, and write JSON lines:", "leaker domain -l domains.txt -s all -j -o results.jsonl"},
		{"Search usernames piped on standard input:", "cat usernames.txt | leaker username"},
		{"Load bash completions into the current shell:", bashLoadCommand},
	} {
		if i > 0 {
			line(".PP")
		}
		text(example.text)
		line(".PP")
		line(".RS")
		line(".nf")
		text(example.command)
		line(".fi")
		line(".RE")
	}

	line(`.SH "AUTHORS"`)
	text(AUTHOR + ".")

	line(`.SH "SEE ALSO"`)
	text("Documentation and source code: https://github.com/vflame6/leaker")

	_, err := io.WriteString(w, b.String())
	return err
}

// roffEscape escapes s as roff text: backslashes and minus signs, and a
// leading dot or quote that roff would read as a request.
func roffEscape(s string) string {
	s = strings.NewReplacer(`\`, `\e`, "-", `\-`).Replace(s)
	if strings.HasPrefix(s, ".") || strings.HasPrefix(s, "'") {
		s = `\&` + s
	}
	return s
}

// sentence ends s with a period.
func sentence(s string) string {
	s = strings.TrimSpace(s)
	if s == "" || strings.HasSuffix(s, ".") {
		return s
	}
	return s + "."
}
