package cmd

import (
	"fmt"
	"io"
	"strings"

	"github.com/alecthomas/kong"
	"github.com/vflame6/leaker/runner"
)

// Value completions, set on a flag or an argument with a complete:"" tag.
// A value without the tag completes its enum choices, if any, or nothing.
const (
	completeFile    = "file"    // file names
	completeSources = "sources" // comma-separated source names and groups
)

// complFlag is a visible flag as the completion scripts see it.
type complFlag struct {
	long, short string // short is "" when the flag has none
	help        string
	takesValue  bool
	repeatable  bool
	complete    string   // completeFile, completeSources or ""
	enum        []string // fixed choices for the value
}

// forms returns the flag as typed: --long and, if it has one, -s.
func (f complFlag) forms() []string {
	if f.short == "" {
		return []string{"--" + f.long}
	}
	return []string{"--" + f.long, "-" + f.short}
}

// complCommand is a visible command and its argument.
type complCommand struct {
	name, help string
	argFile    bool     // the argument completes file names
	argEnum    []string // fixed choices for the argument
}

// complModel is the part of the CLI the completion scripts need.
type complModel struct {
	commands []complCommand
	flags    []complFlag
	sources  []string // choices for complete:"sources"
}

// writeCompletion writes the completion script for shell (bash, zsh or fish),
// generated from the CLI model so it offers exactly this build's commands,
// flags and sources.
func writeCompletion(w io.Writer, app *kong.Application, shell string) error {
	var render func(complModel) string
	switch shell {
	case "bash":
		render = bashCompletion
	case "zsh":
		render = zshCompletion
	case "fish":
		render = fishCompletion
	default:
		return fmt.Errorf("unsupported shell %q: use bash, zsh or fish", shell)
	}
	model, err := newComplModel(app, sourceChoices())
	if err != nil {
		return err
	}
	_, err = io.WriteString(w, render(model))
	return err
}

// sourceChoices lists what -s accepts: the groups, then every source name.
func sourceChoices() []string {
	choices := []string{"online", "all"}
	for _, s := range runner.AllSources {
		choices = append(choices, s.Name())
	}
	return choices
}

func newComplModel(app *kong.Application, sources []string) (complModel, error) {
	model := complModel{sources: sources}
	for _, f := range app.Flags {
		if f.Hidden {
			continue
		}
		kind, err := completeKind(f.Tag)
		if err != nil {
			return complModel{}, fmt.Errorf("flag --%s: %w", f.Name, err)
		}
		flag := complFlag{
			long:       f.Name,
			help:       f.Help,
			takesValue: !f.IsBool() && !f.IsCounter(),
			repeatable: f.IsSlice(),
			complete:   kind,
			enum:       enumChoices(f.Value),
		}
		if f.Short != 0 {
			flag.short = string(f.Short)
		}
		model.flags = append(model.flags, flag)
	}
	for _, c := range app.Children {
		if c.Hidden || c.Type != kong.CommandNode {
			continue
		}
		command := complCommand{name: c.Name, help: c.Help}
		if len(c.Positional) > 0 {
			arg := c.Positional[0]
			kind, err := completeKind(arg.Tag)
			if err != nil {
				return complModel{}, fmt.Errorf("command %s: %w", c.Name, err)
			}
			if kind == completeSources {
				return complModel{}, fmt.Errorf("command %s: complete:%q is for flags", c.Name, kind)
			}
			command.argFile = kind == completeFile
			command.argEnum = enumChoices(arg)
		}
		model.commands = append(model.commands, command)
	}
	return model, nil
}

func completeKind(tag *kong.Tag) (string, error) {
	if tag == nil {
		return "", nil
	}
	switch kind := tag.Get("complete"); kind {
	case "", completeFile, completeSources:
		return kind, nil
	default:
		return "", fmt.Errorf("unknown complete:%q tag, want %q or %q", kind, completeFile, completeSources)
	}
}

func enumChoices(v *kong.Value) []string {
	var choices []string
	for choice := range strings.SplitSeq(v.Enum, ",") {
		if choice = strings.TrimSpace(choice); choice != "" {
			choices = append(choices, choice)
		}
	}
	return choices
}

// commandNames returns the visible command names, in CLI order.
func (m complModel) commandNames() []string {
	names := make([]string, 0, len(m.commands))
	for _, c := range m.commands {
		names = append(names, c.name)
	}
	return names
}

// bashLoadCommand loads the bash completion into the current shell. bash 3.2,
// the macOS /bin/bash, silently ignores "source <(leaker completion bash)".
const bashLoadCommand = `eval "$(leaker completion bash)"`

const bashHeader = `# bash completion for leaker
# Generated by "leaker completion bash". Load it in the current shell with
#   ` + bashLoadCommand + `
# or save it as /usr/share/bash-completion/completions/leaker.

# _leaker_files PREFIX WORD completes file names; PREFIX is kept in front.
_leaker_files() {
    type compopt >/dev/null 2>&1 && compopt -o filenames 2>/dev/null
    local IFS=$'\n'
    COMPREPLY=($(compgen -P "$1" -f -- "$2"))
}

# _leaker_list PREFIX CHOICES WORD completes the last item of a comma-separated
# list; PREFIX and the items before the last comma are kept in front.
_leaker_list() {
    local head="${3%"${3##*,}"}"
    COMPREPLY=($(compgen -P "$1$head" -W "$2" -- "${3##*,}"))
}

_leaker() {
    local cur="${COMP_WORDS[COMP_CWORD]}" prev="" prefix="" assigned="" cmd="" word i
    [ "$COMP_CWORD" -gt 0 ] && prev="${COMP_WORDS[COMP_CWORD-1]}"
    # bash 4+ splits --flag=value into --flag, = and value at COMP_WORDBREAKS.
    if [ "$cur" = "=" ]; then
        cur=""
        assigned=1
    elif [ "$prev" = "=" ] && [ "$COMP_CWORD" -gt 1 ]; then
        prev="${COMP_WORDS[COMP_CWORD-2]}"
        assigned=1
    elif [[ "$cur" == --*=* ]]; then
        # One word: bash 3.2, or "=" removed from COMP_WORDBREAKS. readline
        # replaces only the text after "=" when "=" breaks words.
        prev="${cur%%=*}"
        cur="${cur#*=}"
        assigned=1
        [[ "$COMP_WORDBREAKS" == *=* ]] || prefix="$prev="
    fi

`

func bashCompletion(m complModel) string {
	var b strings.Builder
	b.WriteString(bashHeader)

	// The value of the flag before the cursor.
	var valueFlags []string
	b.WriteString("    case \"$prev\" in\n")
	for _, f := range m.flags {
		if !f.takesValue {
			continue
		}
		pattern := strings.Join(f.forms(), "|")
		valueFlags = append(valueFlags, pattern)
		switch {
		case f.complete == completeFile:
			fmt.Fprintf(&b, "        %s)\n            _leaker_files \"$prefix\" \"$cur\"\n            return ;;\n", pattern)
		case f.complete == completeSources:
			fmt.Fprintf(&b, "        %s)\n            _leaker_list \"$prefix\" %s \"$cur\"\n            return ;;\n", pattern, bashQuote(strings.Join(m.sources, " ")))
		case len(f.enum) > 0:
			fmt.Fprintf(&b, "        %s)\n            COMPREPLY=($(compgen -P \"$prefix\" -W %s -- \"$cur\"))\n            return ;;\n", pattern, bashQuote(strings.Join(f.enum, " ")))
		default:
			fmt.Fprintf(&b, "        %s)\n            return ;;\n", pattern)
		}
	}
	b.WriteString("        *)\n            [ -n \"$assigned\" ] && return ;;\n    esac\n\n")

	// The command, skipping flag values that could look like one.
	b.WriteString("    for ((i = 1; i < COMP_CWORD; i++)); do\n        word=\"${COMP_WORDS[i]}\"\n        case \"$word\" in\n")
	if len(valueFlags) > 0 {
		fmt.Fprintf(&b, "            %s)\n                [ \"${COMP_WORDS[i+1]}\" = \"=\" ] && ((i++))\n                ((i++)) ;;\n", strings.Join(valueFlags, "|"))
	}
	fmt.Fprintf(&b, "            %s)\n                cmd=\"$word\"\n                break ;;\n        esac\n    done\n\n", strings.Join(m.commandNames(), "|"))

	var flagWords []string
	for _, f := range m.flags {
		flagWords = append(flagWords, f.forms()...)
	}
	fmt.Fprintf(&b, "    if [[ \"$cur\" == -* ]]; then\n        COMPREPLY=($(compgen -W %s -- \"$cur\"))\n        return\n    fi\n\n", bashQuote(strings.Join(flagWords, " ")))

	b.WriteString("    case \"$cmd\" in\n")
	fmt.Fprintf(&b, "        \"\")\n            COMPREPLY=($(compgen -W %s -- \"$cur\")) ;;\n", bashQuote(strings.Join(m.commandNames(), " ")))
	for _, c := range m.commands {
		switch {
		case len(c.argEnum) > 0:
			fmt.Fprintf(&b, "        %s)\n            COMPREPLY=($(compgen -W %s -- \"$cur\")) ;;\n", c.name, bashQuote(strings.Join(c.argEnum, " ")))
		case c.argFile:
			fmt.Fprintf(&b, "        %s)\n            _leaker_files \"\" \"$cur\" ;;\n", c.name)
		}
	}
	b.WriteString(`    esac
}

# bash 3.2 has no compopt: let readline treat every candidate as a file name,
# so names with spaces are escaped and directories get a "/".
if type compopt >/dev/null 2>&1; then
    complete -F _leaker leaker
else
    complete -o filenames -F _leaker leaker
fi
`)
	return b.String()
}

// bashQuote quotes s as one single-quoted shell word.
func bashQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func zshCompletion(m complModel) string {
	var b strings.Builder
	b.WriteString(`#compdef leaker
# zsh completion for leaker
# Generated by "leaker completion zsh". Save it as _leaker in a directory on
# $fpath, or load it in the current shell with
#   source <(leaker completion zsh)

_leaker_sources() {
  _values -s , source`)
	for _, s := range m.sources {
		b.WriteString(" " + bashQuote(s))
	}
	b.WriteString(`
}

_leaker() {
  local curcontext="$curcontext" state line ret=1
  local -a flags commands
  flags=(
`)
	for _, f := range m.flags {
		b.WriteString("    " + zshFlagSpec(f) + "\n")
	}
	b.WriteString("  )\n  commands=(\n")
	for _, c := range m.commands {
		b.WriteString("    " + bashQuote(c.name+":"+c.help) + "\n")
	}
	b.WriteString(`  )

  _arguments -C -s -S : $flags \
    '1:command:->command' \
    '*::argument:->argument' && ret=0

  case $state in
    command)
      _describe -t commands 'leaker command' commands && ret=0
      ;;
    argument)
      case $line[1] in
`)
	for _, c := range m.commands {
		action := ""
		switch {
		case len(c.argEnum) > 0:
			action = "(" + strings.Join(c.argEnum, " ") + ")"
		case c.argFile:
			action = "_files"
		}
		arg := ""
		if action != "" {
			arg = " " + bashQuote("1:argument:"+action)
		}
		fmt.Fprintf(&b, "        %s)\n          _arguments -s -S : $flags%s && ret=0\n          ;;\n", c.name, arg)
	}
	b.WriteString(`      esac
      ;;
  esac
  return ret
}

if [ "$funcstack[1]" = "_leaker" ]; then
  _leaker "$@"
else
  compdef _leaker leaker
fi
`)
	return b.String()
}

// zshFlagSpec returns the _arguments spec of a flag, as a shell word list.
func zshFlagSpec(f complFlag) string {
	// The forms of a flag exclude each other; a repeatable flag excludes
	// nothing. --help ends the command line.
	exclude := ""
	switch {
	case f.long == "help":
		exclude = "(- *)"
	case f.repeatable:
		exclude = "*"
	case f.short != "":
		exclude = "(-" + f.short + " --" + f.long + ")"
	}
	optional := "--" + f.long
	short := ""
	if f.short != "" {
		short = "-" + f.short
	}
	if f.takesValue {
		optional += "="
		if short != "" {
			short += "+"
		}
	}
	description := "[" + zshEscape(f.help) + "]"
	value := ""
	if f.takesValue {
		switch {
		case f.complete == completeFile:
			value = ":file:_files"
		case f.complete == completeSources:
			value = ":source:_leaker_sources"
		case len(f.enum) > 0:
			value = ":" + f.long + ":(" + strings.Join(f.enum, " ") + ")"
		default:
			value = ":" + f.long + ": "
		}
	}
	if short == "" {
		return bashQuote(exclude + optional + description + value)
	}
	return bashQuote(exclude) + "{" + short + "," + optional + "}" + bashQuote(description+value)
}

// zshEscape escapes text for the [description] of an _arguments spec.
func zshEscape(s string) string {
	return strings.NewReplacer(`\`, `\\`, "[", `\[`, "]", `\]`, ":", `\:`).Replace(s)
}

func fishCompletion(m complModel) string {
	var b strings.Builder
	b.WriteString(`# fish completion for leaker
# Generated by "leaker completion fish". Save it as
# ~/.config/fish/completions/leaker.fish.

function __leaker_sources
    printf '%s\n'`)
	for _, s := range m.sources {
		b.WriteString(" " + fishQuote(s))
	}
	b.WriteString("\nend\n\ncomplete -c leaker -f\n")

	names := strings.Join(m.commandNames(), " ")
	var fileCommands []string
	for _, c := range m.commands {
		fmt.Fprintf(&b, "complete -c leaker -n %s -a %s -d %s\n",
			fishQuote("not __fish_seen_subcommand_from "+names), c.name, fishQuote(c.help))
	}
	for _, c := range m.commands {
		switch {
		case len(c.argEnum) > 0:
			fmt.Fprintf(&b, "complete -c leaker -n %s -a %s\n",
				fishQuote("__fish_seen_subcommand_from "+c.name), fishQuote(strings.Join(c.argEnum, " ")))
		case c.argFile:
			fileCommands = append(fileCommands, c.name)
		}
	}
	if len(fileCommands) > 0 {
		fmt.Fprintf(&b, "complete -c leaker -n %s -F\n", fishQuote("__fish_seen_subcommand_from "+strings.Join(fileCommands, " ")))
	}

	for _, f := range m.flags {
		b.WriteString("complete -c leaker")
		if f.short != "" {
			b.WriteString(" -s " + f.short)
		}
		b.WriteString(" -l " + f.long)
		if f.takesValue {
			switch {
			case f.complete == completeFile:
				b.WriteString(" -r -F")
			case f.complete == completeSources:
				b.WriteString(" -x -a " + fishQuote("(__fish_complete_list , __leaker_sources)"))
			case len(f.enum) > 0:
				b.WriteString(" -x -a " + fishQuote(strings.Join(f.enum, " ")))
			default:
				b.WriteString(" -x")
			}
		}
		b.WriteString(" -d " + fishQuote(f.help) + "\n")
	}
	return b.String()
}

// fishQuote quotes s as one single-quoted fish word.
func fishQuote(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, "'", `\'`).Replace(s) + "'"
}
